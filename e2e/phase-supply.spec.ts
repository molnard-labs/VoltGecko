import { expect, test } from '@playwright/test';
import { chooseSample, reopenRecentProject } from './startup';

test('single-phase supply drives circuit and device choices and survives reload and archive import', async ({ page }, testInfo) => {
  await page.addInitScript(() => Object.defineProperty(window, 'showSaveFilePicker', { value: undefined, configurable: true }));
  await page.goto('/');
  await chooseSample(page);
  const tab = (name: string) => page.locator('.view-tabs').getByRole('button', { name, exact: true }).click();
  await tab('Elosztó');
  await page.getByRole('button', { name: 'Betáplálás hozzáadása', exact: true }).click();
  await page.locator('.wiring-device-group').filter({ hasText: 'QF1' }).click();
  await page.locator('.electrical-device-fields>summary').click();
  const devicePhase = page.getByLabel('Készülék fázisa', { exact: true });
  await expect(devicePhase.locator('option')).toHaveText(['Nincs kiosztva', 'L']);
  await devicePhase.selectOption('L');
  await tab('Áramkörök');
  const circuitL = page.getByLabel('ÁK1: L vezető', { exact: true });
  const circuitN = page.getByLabel('ÁK1: N vezető', { exact: true });
  const circuitPE = page.getByLabel('ÁK1: PE vezető', { exact: true });
  await expect(page.getByLabel('ÁK1 fázisa', { exact: true })).toHaveCount(0);
  await circuitL.check();
  await circuitN.check();
  await circuitPE.check();
  await page.reload();
  await reopenRecentProject(page);
  await tab('Áramkörök');
  await expect(circuitL).toBeChecked();
  await expect(circuitN).toBeChecked();
  await expect(circuitPE).toBeChecked();
  await tab('Elosztó');
  await page.locator('.wiring-device-group').filter({ hasText: 'QF1' }).click();
  await page.locator('.electrical-device-fields>summary').click();
  await expect(devicePhase).toHaveValue('L');
  await expect(page.locator('.wiring-phase>div>span').first()).toContainText('L');
  await page.getByRole('button', { name: 'Mentés és export', exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: /Projektfájl mentése/ }).click();
  const download = await downloadPromise;
  const archive = testInfo.outputPath('single-phase.vgecko');
  await download.saveAs(archive);
  await expect(page.locator('.busy-overlay')).toHaveCount(0);
  await tab('Áramkörök');
  await circuitL.uncheck();
  await page.locator('input[accept*=".vgecko"]').setInputFiles(archive);
  await expect(page.locator('.project-title')).toContainText('importált másolat');
  await tab('Áramkörök');
  await expect(circuitL).toBeChecked();
  await expect(circuitN).toBeChecked();
  await expect(circuitPE).toBeChecked();
  await tab('Elosztó');
  await page.locator('.wiring-device-group').filter({ hasText: 'QF1' }).click();
  await page.locator('.electrical-device-fields>summary').click();
  await expect(devicePhase).toHaveValue('L');
});
